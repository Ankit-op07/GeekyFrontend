// Dynamic programming, split into 1-D and 2-D because they are learned very
// differently: 1-D is almost always "the answer at i depends on i-1 and i-2",
// which you can find by writing three examples on paper. 2-D needs you to name
// what the two dimensions MEAN before any recurrence makes sense, and that
// naming is the whole skill.
//
// Every problem here should be solved twice — memoised recursion first (which
// is just the brute force plus a cache), then the bottom-up table. Going
// straight to the table teaches you to memorise recurrences instead of
// deriving them, and that falls apart the moment an interviewer changes one
// constraint.

