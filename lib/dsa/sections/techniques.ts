// The four short sections that do not belong to a data structure: greedy,
// intervals, bit manipulation, and matrix/math. They run last not because they
// are hardest but because each is small enough to finish in a few evenings —
// which makes them the right thing to have left when an interview is a week
// away and you want visible progress.
//
// Intervals is separated from greedy deliberately. Almost every interval
// problem is "sort by the right endpoint, then sweep", and that ONE decision —
// sort by start or by end — is what the interviewer is checking. Grouped in
// with general greedy problems, the pattern never becomes visible.

